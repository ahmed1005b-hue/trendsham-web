    /** مرادفات الكلمة وصيغها الإملائية كما قد تُكتب في أسماء المنتجات */
    public static function alternatives(string $word): array
    {
        $word = Normalizer::stem($word);
        $group = [$word];
        foreach (self::SYNONYMS as $set) {
            if (in_array($word, $set, true)) {
                $group = $set;
                break;
            }
        }

        $out = [];
        foreach ($group as $w) {
            $out[] = $w;
            if (str_ends_with($w, 'ه')) {
                $out[] = mb_substr($w, 0, -1).'ة';
            }
            if (str_ends_with($w, 'ي')) {
                $out[] = mb_substr($w, 0, -1).'ى';
            }
            if (str_starts_with($w, 'ا')) {
                $out[] = 'أ'.mb_substr($w, 1);
                $out[] = 'إ'.mb_substr($w, 1);
            }
        }

        return array_values(array_unique($out));
    }

    /** هل الكلمة اسم منتج نعرفه؟ (لاكتشاف نية البحث بلا فعل صريح) */
    public static function knowsProduct(string $token): bool
    {
        $stem = Normalizer::stem($token);
        foreach (self::SYNONYMS as $set) {
            if (in_array($stem, $set, true)) {
                return true;
            }
        }

        return false;
    }

    public static function color(string $token): ?string
    {
        foreach (self::COLORS as $canonical => $forms) {
            if (in_array($token, $forms, true)) {
                return $canonical;
            }
        }

        return null;
    }
