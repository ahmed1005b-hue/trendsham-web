<?php

namespace App\Assistant\Nlp;

/**
 * نوايا البائع. الترتيب مهم:
 * "نصائح لزيد مبيعاتي" نصائح، "طلبات السحب" محفظة، "مبيعاتي من المخزون" مبيعات.
 * كلمات عامة مثل "خلصت" و"نفذ" و"هاي" (= هذه) مستبعدة لأنها تُقال بمعانٍ أخرى.
 */
class SellerIntentDetector
{
    /** @var array<string, list<string>> */
    private const KEYWORDS = [
        'describe' => ['اكتب وصف', 'اكتبلي وصف', 'اكتب لي وصف', 'وصف لمنتج', 'وصف للمنتج', 'ولد وصف', 'ولدلي وصف', 'وصف منتج', 'وصف جديد'],
        'handoff' => ['موظف', 'الدعم', 'دعم فني', 'الاداره', 'احكي مع حدا', 'support'],
        'tips' => ['نصائح', 'نصيحه', 'انصحني', 'نصحني', 'اقتراحات', 'زيد مبيعاتي', 'كيف زيد', 'حسن متجري', 'حسن مبيعاتي'],
        'wallet' => ['رصيد', 'رصيدي', 'محفظه', 'محفظتي', 'طلبات السحب', 'طلب سحب', 'سحب', 'اسحب', 'فلوسي', 'balance'],
        'sales' => ['مبيعات', 'مبيعاتي', 'المبيعات', 'ارباح', 'ارباحي', 'بعت', 'كم بعت', 'ايرادات', 'مدخول', 'مدخولي', 'الكميه المباعه', 'sales'],
        'low_stock' => ['نفاد', 'ينفد', 'نافد', 'قربت تخلص', 'قرب يخلص', 'رح يخلص', 'خلصان', 'مخزون', 'المخزون', 'كميه قليله', 'الكميات القليله', 'ستوك', 'stock'],
        'pending_orders' => ['طلبات', 'الطلبات', 'طلباتي', 'بانتظاري', 'اوردرات', 'طلب جديد', 'طلبات جديده', 'لازم جهز', 'orders'],
        'help' => ['شو بتعمل', 'شو بتقدر', 'شو فيك تعمل', 'مساعده', 'ساعدني', 'help'],
        'thanks' => ['شكرا', 'يسلمو', 'مشكور', 'تسلم', 'thanks', 'يعطيك العافيه'],
        'greeting' => ['مرحبا', 'مرحبه', 'هلا', 'اهلا', 'اهلين', 'السلام', 'صباح الخير', 'مسا الخير', 'مساء الخير', 'hi', 'hello'],
    ];

    /** يُسمح فيها بخطأ إملائي بسيط (كلمات طويلة مميزة) */
    private const FUZZY = ['tips', 'sales'];

    public function __construct(private readonly Normalizer $normalizer) {}

    public function detect(string $message): string
    {
        $text = $this->normalizer->normalize($message);

        foreach (self::KEYWORDS as $intent => $keywords) {
            if ($this->normalizer->matches($text, $keywords, fuzzy: in_array($intent, self::FUZZY, true))) {
                return $intent;
            }
        }

        return 'unknown';
    }
}
